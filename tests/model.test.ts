import test from 'node:test';
import assert from 'node:assert/strict';
import { childSeats, requestSummary, statusLabels } from '../src/model.ts';
import type { AgentSnapshot } from '../src/model.ts';
const sample: AgentSnapshot = { id: 'test', name: '示例', character: 'self', status: 'idle', latestUserRequest: null, childAgentIds: [] };
test('没有子 Agent 时不显示溢出', () => assert.deepEqual(childSeats([]), { visible: [], overflow: 0 }));
test('最多显示两个，超过用 +N 表示', () => assert.deepEqual(childSeats(['a','b','c','d','e']), { visible: ['a','b'], overflow: 3 }));
test('第三个子 Agent 保留为溢出，且不修改输入', () => { const ids = Object.freeze(['a','b','c']); assert.equal(childSeats(ids).overflow, 1); assert.deepEqual(ids,['a','b','c']); });
test('无请求显示占位', () => assert.equal(requestSummary(sample), '尚无用户请求'));
test('显示用户请求内容而非活动摘要', () => assert.equal(requestSummary({...sample, latestUserRequest:{summary:'  请检查布局  ',receivedAt:'2026-11-03T00:00:00Z'}}), '请检查布局'));
test('空请求摘要回退占位', () => assert.equal(requestSummary({...sample,latestUserRequest:{summary:' ',receivedAt:'2026-11-03T00:00:00Z'}}),'尚无用户请求'));
test('状态展示标签齐全', () => assert.equal(Object.keys(statusLabels).length, 4));
